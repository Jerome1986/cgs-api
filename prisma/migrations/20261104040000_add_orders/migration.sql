CREATE TABLE orders (
  id INTEGER NOT NULL AUTO_INCREMENT COMMENT '订单主键',
  order_no VARCHAR(64) NOT NULL COMMENT '平台业务订单号',
  user_id INTEGER NOT NULL COMMENT '购买用户编号',
  product_id INTEGER NOT NULL COMMENT '购买商品编号',
  product_name VARCHAR(200) NOT NULL COMMENT '商品中文名称快照',
  product_type VARCHAR(16) NOT NULL COMMENT '商品类型快照：gold金币充值、membership购买会员',
  amount DECIMAL(10,2) NOT NULL COMMENT '人民币应付金额快照，单位元',
  status VARCHAR(16) NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING未支付、PAID已支付、CANCELLED已取消、FAILED支付失败、COMPLETED已完成',
  payment_id VARCHAR(128) NULL COMMENT '第三方支付流水，未创建支付时为空',
  gold_coins_amount INTEGER NOT NULL DEFAULT 0 COMMENT '金币数量快照，会员订单为0',
  membership_type VARCHAR(16) NOT NULL DEFAULT '' COMMENT '会员类型快照：annual年费、permanent永久，金币订单为空',
  daily_download_limit INTEGER NOT NULL DEFAULT 0 COMMENT '每日下载额度快照，金币订单为0',
  paid_at DATETIME(3) NULL COMMENT '可信支付确认时间',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '创建订单时间',
  updated_at DATETIME(3) NOT NULL COMMENT '更新时间',
  PRIMARY KEY (id),
  UNIQUE INDEX orders_order_no_key (order_no),
  UNIQUE INDEX orders_payment_id_key (payment_id),
  INDEX orders_user_id_created_at_id_idx (user_id, created_at, id),
  INDEX orders_status_created_at_id_idx (status, created_at, id),
  INDEX orders_product_id_idx (product_id),
  CONSTRAINT orders_user_id_fkey FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT orders_product_id_fkey FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE RESTRICT ON UPDATE RESTRICT
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci COMMENT='后台与Electron共享订单及购买快照';
